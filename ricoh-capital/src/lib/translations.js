function deepMerge(base, override) {
  const output = { ...base };
  Object.entries(override || {}).forEach(([key, value]) => {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      output[key] = deepMerge(base?.[key] || {}, value);
    } else {
      output[key] = value;
    }
  });
  return output;
}

function getDictionary(locale) {
  return deepMerge(messages['en-GB'], messages[locale] || {});
}

function getPathValue(object, path) {
  return path.split('.').reduce((acc, key) => (acc && acc[key] != null ? acc[key] : undefined), object);
}

export function translate(locale, key, values = {}) {
  const dictionary = getDictionary(locale);
  const template = getPathValue(dictionary, key) ?? key;
  return Object.entries(values).reduce(
    (output, [token, value]) => output.replaceAll(`{${token}}`, String(value)),
    template,
  );
}
